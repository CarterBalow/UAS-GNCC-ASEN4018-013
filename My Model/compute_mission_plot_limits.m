function limits = compute_mission_plot_limits(positionENU, mission, aoi, cfg)
%COMPUTE_MISSION_PLOT_LIMITS Bound the entire mission with useful padding.
% Inputs and limits use [East, North, Up] in meters.

allEast = [positionENU(:,1); mission.waypointsENU(:,1); ...
    aoi.boundaryEN(:,1); cfg.homeENU(1)];
allNorth = [positionENU(:,2); mission.waypointsENU(:,2); ...
    aoi.boundaryEN(:,2); cfg.homeENU(2)];
allUp = [positionENU(:,3); mission.waypointsENU(:,3); 0; ...
    cfg.flight.searchAltitudeM];

eastPadding = padded_amount(allEast, ...
    cfg.visualization.horizontalPaddingFraction, ...
    cfg.visualization.minimumHorizontalPaddingM);
northPadding = padded_amount(allNorth, ...
    cfg.visualization.horizontalPaddingFraction, ...
    cfg.visualization.minimumHorizontalPaddingM);
upPadding = padded_amount(allUp, ...
    cfg.visualization.verticalPaddingFraction, ...
    cfg.visualization.minimumVerticalPaddingM);

limits.eastM = [min(allEast)-eastPadding, max(allEast)+eastPadding];
limits.northM = [min(allNorth)-northPadding, max(allNorth)+northPadding];
limits.upM = [min(allUp)-upPadding, max(allUp)+upPadding];
limits.paddingM = [eastPadding, northPadding, upPadding];
limits.dataBoundsENU = [min(allEast), max(allEast); ...
                        min(allNorth), max(allNorth); ...
                        min(allUp), max(allUp)];
end

function padding = padded_amount(values, fraction, minimumPadding)
span = max(values)-min(values);
padding = max(minimumPadding, fraction*span);
end
