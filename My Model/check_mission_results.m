function checks = check_mission_results(results, cfg, mission, aoi)
%CHECK_MISSION_RESULTS Evaluate geometric, state, altitude, and speed checks.

position = results.positionENU;
velocity = results.velocityENU;
command = results.velocityCommandENU;
speed = vecnorm(velocity, 2, 2);
commandSpeed = vecnorm(command, 2, 2);

checks.searchWaypointsInsideAOI = all(mission.searchWaypointInsideAOI);
checks.trackSpacingAtOrBelowConfigured = ...
    mission.actualTrackSpacingM <= cfg.aoi.trackSpacingM + 1e-12;
checks.aoiApproximatelyRequiredSize = all([aoi.widthM, aoi.heightM] >= 4.5) && ...
    all([aoi.widthM, aoi.heightM] <= 5.5);
checks.maxAltitudeM = max(position(:,3));
checks.minAltitudeM = min(position(:,3));
checks.maxSpeedMps = max(speed);
checks.maxCommandSpeedMps = max(commandSpeed);
phaseLimits = [cfg.flight.climbSpeedMps, cfg.flight.transitSpeedMps, ...
    cfg.flight.searchSpeedMps, cfg.flight.transitSpeedMps, ...
    cfg.flight.descentSpeedMps];
checks.maxActualSpeedByPhaseMps = nan(1,5);
checks.maxCommandSpeedByPhaseMps = nan(1,5);
for phase = 1:5
    inPhase = round(results.phaseCode) == phase;
    if any(inPhase)
        checks.maxActualSpeedByPhaseMps(phase) = max(speed(inPhase));
        checks.maxCommandSpeedByPhaseMps(phase) = max(commandSpeed(inPhase));
    end
end
checks.phaseSpeedLimitsMps = phaseLimits;
checks.phaseSpeedLimitsMet = all(checks.maxActualSpeedByPhaseMps <= ...
    phaseLimits + cfg.verification.speedToleranceMps) && ...
    all(checks.maxCommandSpeedByPhaseMps <= phaseLimits + 1e-12);
checks.altitudeWithinRequirement = checks.maxAltitudeM <= ...
    cfg.requirements.maxAltitudeAGLM + cfg.verification.altitudeToleranceM && ...
    checks.minAltitudeM >= -cfg.verification.altitudeToleranceM;
checks.speedWithinRequirement = checks.maxSpeedMps <= ...
    cfg.requirements.maxSpeedMps + cfg.verification.speedToleranceMps;
checks.commandSpeedWithinRequirement = checks.maxCommandSpeedMps <= ...
    cfg.requirements.maxSpeedMps + 1e-12;
checks.returnErrorM = norm(position(end,:) - cfg.homeENU);
checks.returnedNearHome = checks.returnErrorM <= cfg.verification.returnToleranceM;
checks.startAltitudeM = position(1,3);
checks.endAltitudeM = position(end,3);
checks.startsOnGround = abs(checks.startAltitudeM-cfg.homeENU(3)) <= ...
    cfg.guidance.landingAltitudeToleranceM;
checks.endsOnGround = abs(checks.endAltitudeM-cfg.homeENU(3)) <= ...
    cfg.guidance.landingAltitudeToleranceM;
checks.startsAndEndsOnGround = checks.startsOnGround && checks.endsOnGround;
checks.missionComplete = any(results.missionComplete > 0.5) || ...
    results.phaseCode(end) == cfg.phase.complete;
checks.phaseCodesVisited = unique(round(results.phaseCode(:))).';
checks.allFlightPhasesVisited = all(ismember(1:5, checks.phaseCodesVisited));
checks.durationSec = results.timeSec(end);
checks.withinEnduranceRequirement = checks.durationSec <= ...
    cfg.requirements.minimumEnduranceSec;
limits = results.plotLimits;
plotPoints = [position; mission.waypointsENU; ...
    [aoi.boundaryEN,zeros(size(aoi.boundaryEN,1),1)]; cfg.homeENU];
checks.plotLimitsContainMission = ...
    all(plotPoints(:,1) >= limits.eastM(1) & plotPoints(:,1) <= limits.eastM(2)) && ...
    all(plotPoints(:,2) >= limits.northM(1) & plotPoints(:,2) <= limits.northM(2)) && ...
    all(plotPoints(:,3) >= limits.upM(1) & plotPoints(:,3) <= limits.upM(2));
checks.plotPaddingM = limits.paddingM;

logicalChecks = [checks.searchWaypointsInsideAOI, ...
    checks.trackSpacingAtOrBelowConfigured, checks.aoiApproximatelyRequiredSize, ...
    checks.altitudeWithinRequirement, checks.speedWithinRequirement, ...
    checks.commandSpeedWithinRequirement, checks.phaseSpeedLimitsMet, ...
    checks.returnedNearHome, checks.startsAndEndsOnGround, ...
    checks.missionComplete, checks.allFlightPhasesVisited, ...
    checks.withinEnduranceRequirement, checks.plotLimitsContainMission];
checks.allPassed = all(logicalChecks);
end
